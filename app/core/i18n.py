# humanrounds.org and Bruno, so a `?lang=` handoff between the two sites
# never lands on a code the other side doesn't know). Codes are PRIMARY
# language subtags, never region-qualified: `Accept-Language` is reduced to
# its primary subtag in `_accept_language_prefs()`, the cookie carries what
