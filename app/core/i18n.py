# generated by `scripts/translate_locales.py` from those two.
LANGUAGE_NAMES = {
    "es": "Español",
    "en": "English",
    "pt": "Português",
    "fr": "Français",
    "it": "Italiano",
    "de": "Deutsch",
    "ru": "\u0420\u0443\u0441\u0441\u043a\u0438\u0439",
    "uk": "\u0423\u043a\u0440\u0430\u0457\u043d\u0441\u044c\u043a\u0430",
    "ja": "日本語",
    "zh": "中文",
}


def language_name(code):
    """The language's own name for a switcher/option label; the upper-cased
    code for one this table doesn't know (a pack-only catalog someone added
    by hand)."""
    code = _safe_lang(code)
    return LANGUAGE_NAMES.get(code) or code.upper()
_COOKIE_MAX_AGE = 60 * 60 * 24 * 365  # 1 year — a language choice is sticky

_CACHE = {}  # lang -> (signature, merged dict)
_SIG = {}    # lang -> (checked_at, signature)
_SIG_TTL = 1.0  # seconds; see _signature()

# Namespaces never shipped to a browser by default. `setup` is the first-run
# installer (server-rendered, one visitor, ~62 keys) and `admin` is the staff
# panel — a patient page inlining either would carry a few dozen KB of strings
