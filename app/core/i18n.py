"""i18n.py — UI string catalogs + active-language resolution (phase 3a of the
open-source rework, 2026-07-30).

Two audiences, one catalog per language — a DIRECTORY of namespace files,
`locales/<lang>/<namespace>.json`, merged into one flat dotted-key dict
(`locales/es/` canonical, `locales/en/` its counterpart). The namespace is
the key's first dotted segment, so `listing.col.proximo` lives in
`listing.json` and nothing has to be told where to look. It is one file per
namespace and not one file per language because a full extraction is a few
thousand keys touched by many hands at once: two monolithic files turn every
concurrent piece of work into the same merge conflict. A flat
`locales/<lang>.json` is still read if present, underneath the directory —
older installs and test fixtures keep working.

  - Python-rendered pages call `t(key, lang)` directly, or leave
    `{{t.<dotted>}}` literals in static HTML/text and let `render(text,
    lang)` resolve them — the same shape `site_identity.py`'s
    `{{sitio.*}}` pipeline already uses, deliberately, so the two token
    families compose in the SAME template without either one needing to
    know about the other (site_identity.render_page() calls both).
  - The client gets the active-language catalog either injected inline
    (a future slice) or fetched from `GET /api/i18n/<lang>.json`
    (`i18n.js`'s `window.SanaI18n.t()` reads it) through
    ``core.i18n_catalog_router``.

Resolution order for "what language is THIS request in" (`resolve_lang`):

    1. `lang` cookie, if it names a currently ENABLED language.
    2. The admin-configured default (config key `LANG_DEFAULT`), if one was
       explicitly set AND it's enabled — this is a deliberate choice, not a
       fallback, so it outranks the browser's own guess.
    3. `Accept-Language`, breaking the tie ONLY when nothing above decided
       (no cookie, no explicit admin default) — among the enabled set.
    4. The first enabled language (normally "es").

`LANGUAGES` (config, comma-separated ids) is the enabled set — filtered to
languages that actually have a catalog file, so a typo degrades instead of
producing an unreachable language. Unset -> just `["es"]`, i.e. the CURRENT
single-language behavior: with only one language enabled, no cookie can
ever change what's served (see step 1 above), so this module is a true
no-op until an admin opts in. That's the invariant the golden-page tests
lean on.

`LANG_SWITCHER_MODE` (config) governs whether — and how — a visitor can
actually change language:

  - "off" (default): no switching surface at all. `?lang=` query params are
    ignored outright (see the native language-switch middleware) — a crafted URL can't expose a
    feature that isn't meant to exist on this installation.
  - "nav": a visible switcher (see nav.js's `SANA_I18N`-gated block,
    injected via `bootstrap_script()`/the `{{i18n_bootstrap}}` token).
  - "secret": no visible switcher, but `/?lang=en` (or any path) still sets
    the cookie and redirects clean — undocumented, for staff to flip a
    session's language without exposing the feature to patients.

Degradation, same criterion as `site_identity.py`/`theme.py`: a missing
catalog file, a DB outage behind `config.get()`, or an unknown key never
raise and never 500 — worst case, `t()` echoes the key back so a gap is
visibly a gap instead of a blank.
"""

