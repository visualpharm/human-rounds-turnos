# renders itself, same as `mail`.
# `backup` belongs to the operator's installer/Settings/System controls.
_CLIENT_EXCLUDE = frozenset({"setup", "admin", "mail", "assistant", "backup"})


# ============================================================== catalogs

def primary_language(lang):
    """The primary subtag of a language code, lowercase (`pt-BR` -> `pt`; `""` when there is none)."""
    return (lang or "").split("-", 1)[0].lower()


def _safe_lang(lang):
    return re.sub(r"[^a-z0-9-]", "", (lang or "").lower())


def _catalog_path(lang):
    """The LEGACY flat catalog, `locales/<lang>.json`. Still read (underneath
    the directory) so an old install or a test fixture that writes one file
    keeps working."""
    return os.path.join(LOCALES_DIR, f"{_safe_lang(lang)}.json")


def _catalog_dir(lang):
    return os.path.join(LOCALES_DIR, _safe_lang(lang))


def _catalog_files(lang):
    """Every file that makes up this language's catalog, flat one first so
    the namespace files win on a duplicate key, then every module-owned
    catalog dir (Tier 2 pilot, 2026-08-05 — see `_module_catalog_files()`)."""
    out = []
    flat = _catalog_path(lang)
    if os.path.isfile(flat):
        out.append(flat)
    directory = _catalog_dir(lang)
    if os.path.isdir(directory):
        out.extend(
            os.path.join(directory, fname)
            for fname in sorted(os.listdir(directory))
            if fname.endswith(".json")
        )
    out.extend(_module_catalog_files(lang))
    return out


def _module_catalog_files(lang):
    """Every `modules/<id>/locales/<lang>/*.json` file a manifest declares
    via its `locales` field (docs/modules.md) — merged in AFTER the central
    tree so nothing here can clobber a platform key, deterministic by
    module id. `app_modules` imports `i18n` at its own top level, so
    importing it back here at THIS module's top level would be circular;
    a local import only pays the cost when catalog resolution actually
    needs it, and it's already covered by `_signature()`'s 1s TTL like
    every other catalog stat in this file."""
    try:
        from app.core import app_modules
    except ImportError:
        return []
    out = []
    for root in app_modules.module_locale_roots():
        d = os.path.join(root, _safe_lang(lang))
        if not os.path.isdir(d):
            continue
        out.extend(
            os.path.join(d, fname)
            for fname in sorted(os.listdir(d))
            if fname.endswith(".json")
        )
    return out


def _signature(lang):
    """(path, mtime) for every file of this language's catalog — what the
    cache compares against.

    Recomputed at most once a second per language. `t()` runs hundreds of
    times per page and the catalog is now ~15 files, so stat-ing all of them
    on every lookup would turn one syscall per string into fifteen. A second
    of staleness only ever matters to a developer editing a JSON file with the
    server up, and they get their change on the next reload."""
    now = time.monotonic()
    cached = _SIG.get(lang)
    if cached and (now - cached[0]) < _SIG_TTL:
        return cached[1]
    sig = []
    for path in _catalog_files(lang):
        try:
            sig.append((path, os.path.getmtime(path)))
        except OSError:
            continue
    sig = tuple(sig)
    _SIG[lang] = (now, sig)
    return sig


def _load_catalog(lang, namespaces=None):
    """The language's whole catalog as one flat dotted-key dict.

    `namespaces` (an iterable of first-segment names) filters the result —
    used by `_client_catalog()` to keep staff-only strings out of a patient's
    HTML. Filtering happens after the merge so the cache stays one entry per
    language, not one per namespace combination."""
    sig = _signature(lang)
    cached = _CACHE.get(lang)
    if cached and cached[0] == sig:
        merged = cached[1]
    else:
        merged = {}
        for path in _catalog_files(lang):
            try:
                with open(path, encoding="utf-8") as f:
                    data = json.load(f)
            except (OSError, ValueError):
                continue
            if isinstance(data, dict):
                # `_comment` is per-file prose about that namespace; it is
                # never a lookup key, and merging 15 of them would leave one
                # arbitrary winner in the catalog.
                merged.update({k: v for k, v in data.items() if k != "_comment"})
        _CACHE[lang] = (sig, merged)
    if namespaces is None:
        return merged
    keep = frozenset(namespaces)
    return {k: v for k, v in merged.items() if k.split(".", 1)[0] in keep}


def namespaces(lang=CANONICAL_LANG):
    """Every namespace this language's catalog defines."""
    return sorted({k.split(".", 1)[0] for k in _load_catalog(lang)})


def client_namespaces(lang=CANONICAL_LANG):
    """What a patient-facing page inlines: everything except the staff-only
    and installer namespaces."""
    return [ns for ns in namespaces(lang) if ns not in _CLIENT_EXCLUDE]


def invalidate():
    """Only for tests: drop the mtime cache so a rewritten fixture reloads."""
    _CACHE.clear()
    _SIG.clear()


def available_locales():
    """Lang codes with an actual catalog on disk — a `locales/<lang>/`
    directory, or the legacy flat `locales/<lang>.json`. Never empty: falls
    back to just the canonical language even if `locales/` is missing."""
    if not os.path.isdir(LOCALES_DIR):
        return [CANONICAL_LANG]
    out = set()
    for entry in os.listdir(LOCALES_DIR):
        full = os.path.join(LOCALES_DIR, entry)
        if entry.endswith(".json") and os.path.isfile(full):
            out.add(entry[:-5])
        elif os.path.isdir(full) and _safe_lang(entry) == entry:
            if any(f.endswith(".json") for f in os.listdir(full)):
                out.add(entry)
    return sorted(out) or [CANONICAL_LANG]


# ============================================================== config

def enabled_languages():
    """Admin-configured enabled set (`LANGUAGES`, comma-separated), filtered
    to languages that actually have a catalog. Default (unset): just the
    canonical language — the change is opt-in."""
    raw = config.get("LANGUAGES", default=CANONICAL_LANG) or CANONICAL_LANG
    have = set(available_locales())
    out, seen = [], set()
    for piece in raw.split(","):
        code = piece.strip().lower()
        if code and code in have and code not in seen:
            seen.add(code)
            out.append(code)
    return out or [CANONICAL_LANG]


def _configured_default():
    """The admin-set `LANG_DEFAULT`, explicit only — None if never
    configured (distinguishes "admin chose es" from "nobody chose
    anything", which is what lets Accept-Language act as a tie-break only
    in the second case)."""
    v = config.get("LANG_DEFAULT")
    v = (v or "").strip().lower()
    return v or None


def default_lang():
    """The language a newcomer with no cookie and no useful Accept-Language
    gets. Public accessor for contexts with no per-request handler (e.g.
    building `<html lang>` for a cached/edge-rendered page)."""
    enabled = enabled_languages()
    configured = _configured_default()
    if configured and configured in enabled:
        return configured
    return enabled[0]


def switcher_mode():
    m = (config.get("LANG_SWITCHER_MODE", default="off") or "off").strip().lower()
    return m if m in ("off", "nav", "secret") else "off"


# ============================================================== resolution

def _cookie_lang(handler):
    if handler is None:
        return None
    try:
        raw = handler.headers.get("Cookie") or ""
    except Exception:  # noqa: BLE001 — a handler-shaped object with no headers
        return None
    for part in raw.split(";"):
        if "=" in part:
            k, v = part.split("=", 1)
            if k.strip() == COOKIE_NAME:
                return v.strip().lower()
    return None


def _accept_language_prefs(handler):
    if handler is None:
        return []
    try:
        raw = handler.headers.get("Accept-Language") or ""
    except Exception:  # noqa: BLE001
        return []
    prefs = []
    for part in raw.split(","):
        tag = part.split(";", 1)[0].strip().lower()
        primary = tag.split("-", 1)[0]
        if primary and primary not in prefs:
            prefs.append(primary)
    return prefs


def resolve_lang(handler=None):
    """The active language for this request. Never raises, never returns a
    language outside the enabled set — see the module docstring for the
    exact precedence."""
    enabled = enabled_languages()
    cookie = _cookie_lang(handler)
    if cookie in enabled:
        return cookie
    configured = _configured_default()
    if configured and configured in enabled:
        return configured
    for pref in _accept_language_prefs(handler):
        if pref in enabled:
            return pref
    return enabled[0]


# ------------------------------------------------------- request-scoped lang
#
# `resolve_lang(handler)` needs the handler, and most page builders never see
# one: `site_shell._shell()` is called by ~20 functions that each receive
# only their own data. Threading a handler through all of them (and through
# preparation.py, appointment_offer.py, modules/intake/…) to reach the one
# place that renders `<html lang>` would be a very wide change for one value
# that is constant for the whole request.
#
# So the language is resolved ONCE per request, in routing.dispatch(), and
# read from here by anything that renders. A ContextVar rather than a module
# global because the server is threaded: each thread gets its own value, and
# `dispatch()` resets it in a `finally` so a later render on a recycled
# thread (a daemon, a background task) can never inherit a visitor's cookie.

_ACTIVE = contextvars.ContextVar("sana_i18n_active", default=None)


def bind(handler=None):
    """Resolve and remember this request's language. Returns a token to pass
    back to `unbind()` — the pair is what routing.dispatch() wraps every
    request in."""
    lang = resolve_lang(handler)
    return lang, _ACTIVE.set(lang)


def unbind(token):
    try:
        _ACTIVE.reset(token)
    except (ValueError, LookupError):  # reset out of order — harmless
        _ACTIVE.set(None)


def bind_lang(lang):
    """Force-bind an explicit language for the current context, bypassing
    `resolve_lang()` entirely (no handler, no cookie, no Accept-Language).

    `bind()` is for a real request, where the language has to be DISCOVERED.
    Offline tooling that has to render pack content in a language nobody
    requested over HTTP — `scripts/search_examples.py` building the
    per-language search-chip corpus — already knows which language it wants;
    this is that case. Same (lang, token) / `unbind()` contract as `bind()`,
    so callers don't need two code paths."""
    lang = (lang or CANONICAL_LANG).strip().lower()
    return lang, _ACTIVE.set(lang)


def active():
    """This request's language, or the resolution with no request context
    (the canonical language on a single-language installation, which is every
    installation that hasn't opted in)."""
    return _ACTIVE.get() or resolve_lang(None)


# ============================================================== t() / render()

_T_PLACEHOLDER_RE = re.compile(r"\{\{t\.([a-zA-Z0-9_.]+)\}\}")


def raw(key, lang=None):
    """String lookup, no variable substitution: `lang` catalog -> canonical
    (`es`) catalog -> the key itself (a missing translation stays visibly
    wrong instead of rendering blank)."""
    # `key in cat`, no `cat.get(key)`/truthiness: una traducción DELIBERADAMENTE
    # vacía ("" — un idioma que no necesita el prefijo que el castellano sí
    # necesita, ver admin.shell.gate.brand_pre) es una clave PRESENTE, no
    # faltante, y no puede caer al castellano sólo por ser falsy en Python.
    lang = (lang or CANONICAL_LANG).lower()
    cat = _load_catalog(lang)
    if key in cat:
        return cat[key]
    if lang != CANONICAL_LANG:
        canon = _load_catalog(CANONICAL_LANG)
        if key in canon:
            return canon[key]
    return key


def t(key, lang=None, **variables):
    """`raw(key, lang)` with `{name}` substitution — same deliberately-not-
    str.format approach as `prompts._substitute` (catalog strings can carry
    literal braces from copy/pasted content)."""
    text = raw(key, lang)
    for k, v in variables.items():
        text = text.replace("{" + k + "}", str(v))
    return text


def t_or(key, default, lang=None, **variables):
    """`t(key, lang)`, but a key that isn't in any catalog renders `default`
    instead of the key itself — the Python twin of `SanaI18n.t(key, vars,
    fallback)`. For call sites that already hold the canonical string and
    only want the catalog when it has something better to say."""
    text = raw(key, lang)
    if text == key:
        text = default
    for k, v in variables.items():
        text = text.replace("{" + k + "}", str(v))
    return text


_PLACEHOLDER = re.compile(r"\{[A-Za-z_]+\}")
_SENTENCE = re.compile(r"[.,;:?!¿¡]")


def _singular_fits(text, count):
    """May the `_one` text stand for `count`, whose category is «one»? A text
    with a placeholder or a bare unit word (at most two words, no sentence
    punctuation: «médico», «turno» printed after the caller's number) — for
    any such count, the 21 of Russian included; a whole singular phrase with
    no number in it («¿Aprobar la solicitud…?») only for exactly 1. Twin of
    i18n.mjs singularFits()."""
    if _plural_number(count) == 1 or _PLACEHOLDER.search(text):
        return True
    return len(text.split()) <= 2 and not _SENTENCE.search(text)


def _plural_number(count):
    """`count` as a float, or None when it is not a number (the JS twin
    parses a formatted string the same way: decimal comma accepted)."""
    if count is None or isinstance(count, bool):
        return None
    if isinstance(count, (int, float)):
        return float(count)
    try:
        return float(str(count).strip().replace(",", "."))
    except ValueError:
        return None


def plural_category(count, lang=None):
    """The CLDR category of `count` in `lang`, the Python twin of
    static/platform/i18n.mjs's pluralCategory() (Intl.PluralRules) for the
    ten shipped languages. "one": 1 in Spanish, English, Italian and German;
    0 and 1 (integer part) in French and Portuguese; 1, 21, 31… but not 11
    in Russian and Ukrainian; never in Japanese and Chinese. Russian and
    Ukrainian also have "few" (2–4, 22–24… but not 12–14) and "many" (0,
    5–20, 25–30…); a fraction there is "other". Every other language's
    few/many (French and Spanish «many» for a million) folds into "other":
    only the Russian and Ukrainian catalogs carry `_few`/`_many` keys.
    `tests/test_i18n_plural.py` and `tests/i18n-plural.test.mjs` hold the
    same table (tests/fixtures/plural-one.json) so the two halves cannot
    drift."""
    num = _plural_number(count)
    if num is None or num != num or num in (float("inf"), float("-inf")):
        return "other"
    lang = primary_language(lang or CANONICAL_LANG)
    whole = num == int(num)
    i = int(abs(num))
    if lang in ("ja", "zh"):
        return "other"
    if lang in ("fr", "pt"):
        return "one" if i in (0, 1) else "other"
    if lang in ("ru", "uk"):
        if not whole:
            return "other"
        if i % 10 == 1 and i % 100 != 11:
            return "one"
        if 2 <= i % 10 <= 4 and not 12 <= i % 100 <= 14:
            return "few"
        return "many"
    return "one" if whole and i == 1 else "other"


# How a number is written in each shipped language: (thousands, decimal).
# The Python twin of static/platform/i18n.mjs's NUM_SEPS; the table is the
# CLDR grouping of each language with grouping always on, so «4.188» reads
# like «10.238» (Spanish CLDR leaves a four-digit number ungrouped, and the
# panel printed «4188 de 10238» next to «4.185» — ui-expert 2026-11-15).
_NUM_SEPS = {
    "en": (",", "."), "ja": (",", "."), "zh": (",", "."),
    "fr": (" ", ","), "ru": (" ", ","), "uk": (" ", ","),
}
_NUM_SEPS_DEFAULT = (".", ",")


def format_number(n, decimals=1, lang=None):
    """`n` in the language's digits: thousands grouped, at most `decimals`
    decimals and never a trailing zero («44,5», «1.466», not «1.466,0»).
    The one implementation behind `format.number()`; twin of i18n.mjs's
    formatNumber(), parity-held by tests/fixtures/number-format.json.
    None, "" and non-numbers render ""."""
    from decimal import Decimal, ROUND_HALF_UP, InvalidOperation, localcontext
    if n is None or n == "" or isinstance(n, bool):
        return ""
    try:
        # A float is taken at its shortest decimal form, as Intl does: 1.005
        # rounds half-up to 1.01 on both sides.
        v = Decimal(repr(n)) if isinstance(n, float) else Decimal(n) if isinstance(n, int) else Decimal(str(n).strip())
    except (InvalidOperation, ValueError):
        return ""
    if not v.is_finite():
        return ""
    try:
        with localcontext() as ctx:
            # room for every digit of a large value (1e30 has 31)
            ctx.prec = max(28, v.adjusted() + int(decimals) + 2)
            q = v.quantize(Decimal(1).scaleb(-int(decimals)), rounding=ROUND_HALF_UP)
    except InvalidOperation:
        return ""
    text = format(q, "f")
    neg = text.startswith("-")
    text = text.lstrip("-")
    whole, _, frac = text.partition(".")
    frac = frac.rstrip("0")
    if neg and (whole.strip("0") or frac):
        sign = "-"
    else:
        sign = ""
    group, dec = _NUM_SEPS.get(primary_language(lang or active()), _NUM_SEPS_DEFAULT)
    parts = []
    while len(whole) > 3:
        parts.insert(0, whole[-3:])
        whole = whole[:-3]
    parts.insert(0, whole)
    return sign + group.join(parts) + (dec + frac if frac else "")


def format_percent(n, lang=None):
    """A percentage with its sign glued on («52%», the form the panel's
    catalog already uses): one decimal only where it changes the reading —
    under 10 («4,3%»), and near 100 where rounding would claim «100%» for
    less than all («99,6%»). Twin of i18n.mjs's formatPercent()."""
    from decimal import Decimal, ROUND_HALF_UP, InvalidOperation
    if n is None or n == "" or isinstance(n, bool):
        return ""
    try:
        v = float(n)
    except (TypeError, ValueError):
        return ""
    if v != v or v in (float("inf"), float("-inf")):
        return ""
    a = abs(v)
    decimals = 1 if a < 10 else 0
    # Short of 100 never reads «100%»: as many decimals as it takes (99,95%).
    while a < 100 and decimals < 6 and Decimal(repr(a)).quantize(Decimal(1).scaleb(-decimals), rounding=ROUND_HALF_UP) >= 100:
        decimals += 1
    return format_number(v, decimals, lang) + "%"


def tn_or(key, count, one, other, lang=None, /, **variables):
    """Number agreement for a «N + noun» string — the Python twin of
    i18n.mjs's tn(). `key_one` when `count` is singular in `lang`
    (plural_category), `key` otherwise, with `one`/`other` the canonical
    Spanish texts (like t_or's default). `{n}` is filled with `count` unless
    the caller passes a formatted `n=`. A `key_one` text with no placeholder
    at all — a whole singular phrase («¿Aprobar la solicitud…?») — is used
    only for exactly 1, never for the 0 of French or the 21 of Russian; a
    bare unit word («médico») serves every «one» count (_singular_fits).
    A Russian or Ukrainian «few»/«many» count reads `key_few`/`key_many`
    (2, 3, 4 and 5–20 take different words) when the catalog has it, `key` otherwise."""
    # A numeric count is written in the language's digits («1.214», not
    # «1214»); a caller that formats its own n= keeps it.
    if isinstance(count, (int, float)) and not isinstance(count, bool):
        variables.setdefault("n", format_number(count, 1, lang))
    else:
        variables.setdefault("n", count)
    category = plural_category(count, lang)
    if category in ("few", "many"):
        text = raw(key + "_" + category, lang)
        if text != key + "_" + category:
            for k, v in variables.items():
                text = text.replace("{" + k + "}", str(v))
            return text
    if category == "one":
        text = raw(key + "_one", lang)
        if text == key + "_one":
            text = one
        if _singular_fits(text, count):
            for k, v in variables.items():
                text = text.replace("{" + k + "}", str(v))
            return text
    return t_or(key, other, lang, **variables)


def render(text, lang=None):
    """Replaces every `{{t.<dotted>}}` in `text` with `t(dotted, lang)`,
    HTML-escaped — the `{{t.*}}` sibling of `site_identity.render()`'s
    `{{sitio.*}}`."""
    def _sub(m):
        return _html.escape(str(t(m.group(1), lang)), quote=True)
    return _T_PLACEHOLDER_RE.sub(_sub, text)


# ============================================================== <html lang>

_LANG_ATTR_TOKEN = "{{lang}}"


def inject_html_lang(text, lang):
    """Resolves the `{{lang}}` placeholder some templates carry in
    `<html lang="{{lang}}" ...>` — the `{{t.*}}` pipeline's sibling of
    `theme.inject()`'s `{{tema}}`. A no-op on text that doesn't carry the
    token (every page NOT wired into this proof slice yet)."""
    if not text or _LANG_ATTR_TOKEN not in text:
        return text
    return text.replace(_LANG_ATTR_TOKEN, lang)


# ============================================================== JS bootstrap

_BOOTSTRAP_PLACEHOLDER = "{{i18n_bootstrap}}"


def bootstrap_script(handler=None, lang=None, namespaces=None,
                     exclude_prefixes=()):
    """A small inline `<script>` exposing `window.SANA_I18N` (active
    language, enabled set, switcher mode, AND the active catalog) to client
    JS — `nav.js`'s language switcher and `i18n.js`'s shim both read it.

    A page served in a NON-canonical language carries its catalog INLINE
    (2026-08-04). The fetch path made `SanaI18n.t()` asynchronously correct
    only: until `/api/i18n/<lang>.json` came back, `t()` returned the raw
    dotted key, so any string rendered at parse time or on an early click
    could flash `home.results.empty` at a visitor. That was the documented
    blocker on converting any JS literal at all
    (docs/architecture/i18n.md, "Why JS literals are still untouched").
    Inline, `t()` is correct from first paint.

    A page in the canonical language carries no catalog at all — see
    `_client_catalog`.

    `namespaces` limits what goes inline; the default leaves out the staff
    and installer namespaces. An admin page passes its own set."""
    lang = lang or resolve_lang(handler)
    payload = {
        "active": lang,
        "enabled": enabled_languages(),
        "mode": switcher_mode(),
        "default": default_lang(),
        "catalog": _client_catalog(lang, namespaces, exclude_prefixes),
    }
    return "<script>window.SANA_I18N=" + json.dumps(payload, ensure_ascii=False) + ";</script>"


def _client_catalog(lang, namespaces=None, exclude_prefixes=()):
    """The active catalog, with the canonical language filled in underneath
    so a key translated in `es` but missing from `en` still renders real text
    instead of the key — the same fallback chain `raw()` applies server-side,
    resolved once here so the client never needs a second lookup.

    Empty whenever the page is being served in the canonical language —
    which is most page loads on most installations. Every
    `SanaI18n.t(key, vars, fallback)` call site passes the canonical literal
    it replaced as `fallback` (enforced by tests/i18n-fallbacks.test.mjs), so
    with no catalog those pages render exactly the bytes they rendered before
    they were translated. Shipping the canonical catalog would only restate
    what the JS already says, at a few KB per page, and it would put every
    interface string of the whole site into the HTML of every page."""
    runtime = _runtime_client_overrides(lang, namespaces)
    prefixes = tuple(str(prefix) for prefix in exclude_prefixes if prefix)
    if lang == CANONICAL_LANG:
        return {key: value for key, value in runtime.items()
                if not key.startswith(prefixes)} if prefixes else runtime
    if namespaces is None:
        namespaces = client_namespaces(CANONICAL_LANG)
    merged = dict(_load_catalog(CANONICAL_LANG, namespaces))
    # Sin filtro de "if v": una clave AUSENTE del catálogo del idioma ya queda
    # afuera de .items() (ahí sigue funcionando el fallback a castellano de
    # arriba) — pero una clave PRESENTE con valor deliberadamente vacío (""),
    # como admin.shell.gate.brand_pre en inglés, es una traducción real, no
    # una faltante, y filtrarla por ser falsy la devolvía en castellano (mismo
    # bug que tenía raw(), ver ahí).
    merged.update(_load_catalog(lang, namespaces))
    merged.update(runtime)
    if prefixes:
        merged = {key: value for key, value in merged.items()
                  if not key.startswith(prefixes)}
    return merged


def _runtime_client_overrides(lang, namespaces=None):
    """Small admin-authored client strings layered over file catalogs.

    The chat greeting is the first such setting. It stays inside the normal
    inline catalog so first paint remains synchronous and does not grow a
    settings fetch or a visible copy swap after the panel opens.
    """
    if namespaces is not None and "chat" not in namespaces:
        return {}
    key = "CHAT_GREETING_" + str(lang or CANONICAL_LANG).strip().upper()
    value = config.get(key)
    return {"chat.greeting": value} if value not in (None, "") else {}


def inject_bootstrap(text, handler=None, lang=None, namespaces=None,
                     exclude_prefixes=()):
    """`namespaces` overrides what goes inline (see `bootstrap_script`) — an
    admin page passes its own set (`client_namespaces() + ["admin"]`, the
    staff namespace `_CLIENT_EXCLUDE` otherwise keeps off every patient
    page). Default `None` keeps every existing caller's behavior unchanged."""
    if not text or _BOOTSTRAP_PLACEHOLDER not in text:
        return text
    return text.replace(_BOOTSTRAP_PLACEHOLDER,
                        bootstrap_script(handler, lang, namespaces,
                                         exclude_prefixes))


# ============================================================== language switching
#
# GET <any path>?lang=<code> sets the cookie + a clean redirect, when
#   switching is actually enabled (mode != "off" and >1 language enabled).
#   This is BOTH the "secret URL" mode's entire mechanism and what the
#   "nav" mode's visible links point at — the difference between the two
#   modes is only whether a switcher renders, never how switching works.

def lang_switch_redirect(query_string, path):
    """Pure decision for a ``?lang=`` switch request (native-migration
    campaign, F2/F9 2026-08-26): takes an already-parsed query string and
    path, returns ``(location, set_cookie_header)`` when the switch applies,
    else ``None`` — no handler object, no write protocol. Native callers
    (`core.site_identity_router`, the patient_web routers) build the actual
    redirect Response themselves."""
    vals = parse_qs(query_string or "").get("lang")
    if not vals:
        return None
    if switcher_mode() == "off":
        return None
    enabled = enabled_languages()
    if len(enabled) < 2:
        return None
    lang = vals[0].strip().lower()
    if lang not in enabled:
        return None
    cookie = f"{COOKIE_NAME}={lang}; Max-Age={_COOKIE_MAX_AGE}; Path=/; SameSite=Lax"
    return (path or "/", cookie)


# F9's routers landed referencing this name for the same decision — one
# implementation, two spellings, kept until both families converge.
resolve_lang_switch = lang_switch_redirect
