#!/usr/bin/env python3
"""scripts/build_centers_map.py — the home page's map of the health centers,
drawn ONCE from OpenStreetMap and served from our own server.

Why a file and not a map widget: a live tile widget is dozens of requests to a
third party on every visit (there is no CDN in front of the site and a patient
on a phone pays each one), it tells that third party who looks at a health
site, and its look is the provider's, not ours. The streets of a town change
over years, so the drawing is a data-pack asset like the center photos:
`centros-mapa.svg` next to `centros-mapa.json`, regenerated by hand when a
center opens somewhere new (decision log, 2026-11-05).

The pack's `centros-mapa.json` is both the input and the output:

  input   "pins":  {"<center slug>": {"lat": …, "lng": …, "place": "<street key>"}}
                   where each center is. `place` is the center's street key
                   (`site_centers._place_key`) the point was taken for: when
                   the panel moves the center to another address the point no
                   longer applies and the center leaves the map for the list
                   under it, instead of pointing at its old door. Coordinates
                   typed in the panel (`lat`/`lng` of the center) win anyway.
          "areas": [{"name": "Ostende", "lat": …, "lng": …}] — town/area names
                   painted on the map (optional).
          "margin": how many times the spread of the pins the drawing covers
                   on each axis (default 2.6): room for the labels and for
                   both the tall phone crop and the wide desktop crop.
  output  "svg", "bbox" [west, south, east, north], "width", "height",
          "attribution", "attribution_url", "osm_date".

The drawing (black and white, product owner 2026-11-05): white land, the sea and
lakes in a light grey, streets in greys by importance, nothing else — no
street names (the centers' labels are the only text that matters and they are
HTML, laid over the image at the size the patient can read), no icons.
Strokes are `non-scaling-stroke`, so a street is as thick on a phone as on a
desktop whatever the crop.

Usage:
  python3 scripts/build_centers_map.py <pack dir> [--cache file.json] [--refresh]

`--cache` keeps the Overpass answer (default: next to the system temp dir) so
re-styling does not hit the public Overpass server again; `--refresh` fetches
anew. Data © OpenStreetMap contributors, ODbL — the attribution is written into
the JSON and shown on the map.
"""

import argparse
import datetime
import json
import math
import os
import sys
import tempfile
import urllib.parse
import urllib.request

OVERPASS = "https://overpass-api.de/api/interpreter"
SPEC = "centros-mapa.json"
SVG = "centros-mapa.svg"
WIDTH = 1000.0           # SVG user units across the drawing
TOLERANCE = 0.18         # simplification, in user units
DEFAULT_MARGIN = 2.6

# highway=* → drawing class. Anything else (footways, paths, tracks, steps,
# construction…) is left out: they are not how a patient arrives.
ROADS = {
    "motorway": "a", "trunk": "a", "primary": "a",
    "motorway_link": "a", "trunk_link": "a", "primary_link": "a",
    "secondary": "b", "secondary_link": "b", "tertiary": "b", "tertiary_link": "b",
    "unclassified": "c", "residential": "c", "living_street": "c", "road": "c",
    "pedestrian": "c",
    "service": "d",
}

STYLE = (
    "path{fill:none;stroke-linecap:round;stroke-linejoin:round;vector-effect:non-scaling-stroke}"
    ".sea,.lake{fill:#e4e4e4;stroke:none}"
    ".sand{fill:#f3f3f3;stroke:none}"
    ".park{fill:#f0f0f0;stroke:none}"
    ".river{stroke:#d6d6d6;stroke-width:3}"
    ".coast{stroke:#9a9a9a;stroke-width:1.2}"
    ".d{stroke:#e2e2e2;stroke-width:.8}"
    ".c{stroke:#c4c4c4;stroke-width:1.1}"
    ".b{stroke:#8c8c8c;stroke-width:2}"
    ".a{stroke:#4a4a4a;stroke-width:3}"
)


def _bbox(pins, margin):
    lats = [p["lat"] for p in pins.values()]
    lngs = [p["lng"] for p in pins.values()]
    lat0 = (min(lats) + max(lats)) / 2
    lng0 = (min(lngs) + max(lngs)) / 2
    k = math.cos(math.radians(lat0))
    span_km = max((max(lats) - min(lats)) * 111.32, (max(lngs) - min(lngs)) * 111.32 * k, 0.8)
    half = span_km * margin / 2
    dlat = half / 111.32
    dlng = half / (111.32 * k)
    return [round(lng0 - dlng, 6), round(lat0 - dlat, 6), round(lng0 + dlng, 6), round(lat0 + dlat, 6)]


def _query(bbox):
    w, s, e, n = bbox
    b = f"({s},{w},{n},{e})"
    hw = "|".join(sorted(ROADS))
    return (
        "[out:json][timeout:180];("
        f'way["highway"~"^({hw})$"]{b};'
        f'way["natural"="coastline"]{b};'
        f'way["natural"~"^(water|beach|sand)$"]{b};'
        f'relation["natural"="water"]{b};'
        f'way["waterway"~"^(river|canal)$"]{b};'
        f'way["leisure"~"^(park|golf_course)$"]{b};'
        ");out geom;"
    )


def fetch(bbox, cache, refresh=False):
    if cache and os.path.isfile(cache) and not refresh:
        with open(cache) as f:
            data = json.load(f)
        if data.get("_bbox") == bbox:
            return data
    body = urllib.parse.urlencode({"data": _query(bbox)}).encode()
    req = urllib.request.Request(OVERPASS, data=body, headers={"User-Agent": "human-rounds-centers-map/1"})
    with urllib.request.urlopen(req, timeout=240) as r:
        data = json.loads(r.read())
    data["_bbox"] = bbox
    if cache:
        with open(cache, "w") as f:
            json.dump(data, f)
    return data


class Projection:
    def __init__(self, bbox):
        self.w, self.s, self.e, self.n = bbox
        k = math.cos(math.radians((self.s + self.n) / 2))
        self.width = WIDTH
        self.height = round(WIDTH * (self.n - self.s) / ((self.e - self.w) * k), 1)

    def xy(self, lat, lng):
        return ((lng - self.w) / (self.e - self.w) * self.width,
                (self.n - lat) / (self.n - self.s) * self.height)


def _rdp(pts, tol):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        i, j = stack.pop()
        (x1, y1), (x2, y2) = pts[i], pts[j]
        dx, dy = x2 - x1, y2 - y1
        norm = math.hypot(dx, dy) or 1e-9
        best, idx = -1.0, -1
        for k in range(i + 1, j):
            x0, y0 = pts[k]
            d = abs(dy * x0 - dx * y0 + x2 * y1 - y2 * x1) / norm
            if d > best:
                best, idx = d, k
        if best > tol and idx > 0:
            keep[idx] = True
            stack.append((i, idx))
            stack.append((idx, j))
    return [p for p, k in zip(pts, keep) if k]


def _clip_runs(pts, W, H):
    """Pieces of the polyline inside [0,W]x[0,H] (Liang–Barsky per segment)."""
    runs, cur = [], []
    for (x1, y1), (x2, y2) in zip(pts, pts[1:]):
        t0, t1 = 0.0, 1.0
        dx, dy = x2 - x1, y2 - y1
        ok = True
        for p, q in ((-dx, x1), (dx, W - x1), (-dy, y1), (dy, H - y1)):
            if p == 0:
                if q < 0:
                    ok = False
                    break
                continue
            r = q / p
            if p < 0:
                t0 = max(t0, r)
            else:
                t1 = min(t1, r)
        if not ok or t0 > t1:
            if cur:
                runs.append(cur)
                cur = []
            continue
        a = (x1 + t0 * dx, y1 + t0 * dy)
        b = (x1 + t1 * dx, y1 + t1 * dy)
        if not cur:
            cur = [a]
        cur.append(b)
        if t1 < 1.0:
            runs.append(cur)
            cur = []
    if cur:
        runs.append(cur)
    return [r for r in runs if len(r) > 1]


def _clip_ring(pts, W, H):
    """Sutherland–Hodgman: a polygon ring clipped to the drawing."""
    def clip(poly, inside, inter):
        out = []
        for i, cur in enumerate(poly):
            prev = poly[i - 1]
            if inside(cur):
                if not inside(prev):
                    out.append(inter(prev, cur))
                out.append(cur)
            elif inside(prev):
                out.append(inter(prev, cur))
        return out

    def ix(x):
        return lambda a, b: (x, a[1] + (b[1] - a[1]) * (x - a[0]) / ((b[0] - a[0]) or 1e-9))

    def iy(y):
        return lambda a, b: (a[0] + (b[0] - a[0]) * (y - a[1]) / ((b[1] - a[1]) or 1e-9), y)

    poly = list(pts)
    for inside, inter in ((lambda p: p[0] >= 0, ix(0)), (lambda p: p[0] <= W, ix(W)),
                          (lambda p: p[1] >= 0, iy(0)), (lambda p: p[1] <= H, iy(H))):
        if not poly:
            break
        poly = clip(poly, inside, inter)
    return poly


def _perimeter_t(p, W, H):
    x, y = p
    eps = 1e-6
    if abs(y) < eps:
        return x
    if abs(x - W) < eps:
        return W + y
    if abs(y - H) < eps:
        return W + H + (W - x)
    return 2 * W + H + (H - y)


def _sea_polygons(chains, W, H):
    """The sea from the coastline. OSM draws the coastline with the land on
    its LEFT, so the sea is on the right: each piece of coast that crosses the
    drawing is closed by walking the frame clockwise from where it leaves back
    to where it entered."""
    corners = [(0.0, (0.0, 0.0)), (W, (W, 0.0)), (W + H, (W, H)), (2 * W + H, (0.0, H))]
    per = 2 * (W + H)
    out = []
    for chain in chains:
        for run in _clip_runs(chain, W, H):
            ta = _perimeter_t(run[0], W, H)
            tb = _perimeter_t(run[-1], W, H)
            ring = list(run)
            t = tb
            end = ta if ta > tb else ta + per
            for base in (0, per):
                for ct, c in corners:
                    if t < ct + base < end:
                        ring.append(c)
            out.append(ring)
    return out


def _chains(ways):
    """Joins coastline ways end to start into continuous lines."""
    segs = [list(w) for w in ways if len(w) > 1]
    chains = []
    while segs:
        cur = segs.pop()
        grown = True
        while grown:
            grown = False
            for i, s in enumerate(segs):
                if s[0] == cur[-1]:
                    cur += s[1:]
                elif s[-1] == cur[0]:
                    cur = s[:-1] + cur
                else:
                    continue
                segs.pop(i)
                grown = True
                break
        chains.append(cur)
    return chains


def _num(v):
    s = f"{v:.1f}"
    if s.endswith(".0"):
        s = s[:-2]
    if s.startswith("0."):
        s = s[1:]
    elif s.startswith("-0."):
        s = "-" + s[2:]
    return s or "0"


def _path(pts, close=False):
    """Relative path data, one decimal: the shortest text for many short lines."""
    q = [(round(x, 1), round(y, 1)) for x, y in pts]
    out = [f"M{_num(q[0][0])} {_num(q[0][1])}"]
    rel = []
    for (x1, y1), (x2, y2) in zip(q, q[1:]):
        dx, dy = round(x2 - x1, 1), round(y2 - y1, 1)
        if dx == 0 and dy == 0:
            continue
        rel.append(f"{_num(dx)}{' ' if dy >= 0 else ''}{_num(dy)}")
    if not rel:
        return ""
    out.append("l" + " ".join(rel).replace(" -", "-"))
    if close:
        out.append("z")
    return "".join(out)


def render(osm, proj):
    W, H = proj.width, proj.height
    layers = {k: [] for k in ("sea", "lake", "sand", "park", "river", "coast", "d", "c", "b", "a")}
    coast = []

    def pts_of(geom):
        return [proj.xy(g["lat"], g["lon"]) for g in geom if g]

    for el in osm.get("elements", []):
        tags = el.get("tags") or {}
        if el["type"] == "relation":
            if tags.get("natural") == "water":
                for m in el.get("members", []):
                    if m.get("role") == "outer" and m.get("geometry"):
                        ring = _clip_ring(_rdp(pts_of(m["geometry"]), TOLERANCE), W, H)
                        if len(ring) > 2:
                            layers["lake"].append(_path(ring, close=True))
            continue
        geom = el.get("geometry") or []
        if not geom:
            continue
        pts = pts_of(geom)
        nat = tags.get("natural")
        if nat == "coastline":
            coast.append(pts)
            continue
        closed = len(pts) > 3 and pts[0] == pts[-1]
        if nat == "water" and closed:
            cls = "lake"
        elif nat in ("beach", "sand") and closed:
            cls = "sand"
        elif tags.get("leisure") in ("park", "golf_course") and closed:
            cls = "park"
        elif tags.get("waterway") in ("river", "canal"):
            for run in _clip_runs(_rdp(pts, TOLERANCE), W, H):
                layers["river"].append(_path(run))
            continue
        else:
            cls = ROADS.get(tags.get("highway"))
            if not cls:
                continue
            for run in _clip_runs(_rdp(pts, TOLERANCE), W, H):
                p = _path(run)
                if p:
                    layers[cls].append(p)
            continue
        ring = _clip_ring(_rdp(pts, TOLERANCE), W, H)
        if len(ring) > 2:
            layers[cls].append(_path(ring, close=True))

    chains = [_rdp(c, TOLERANCE) for c in _chains(coast)]
    for ring in _sea_polygons(chains, W, H):
        layers["sea"].append(_path(ring, close=True))
    for c in chains:
        for run in _clip_runs(c, W, H):
            layers["coast"].append(_path(run))

    body = [f'<rect width="{_num(W)}" height="{_num(H)}" fill="#fff"/>']
    for cls in ("park", "sand", "sea", "lake", "river", "d", "c", "b", "a", "coast"):
        d = "".join(p for p in layers[cls] if p)
        if d:
            body.append(f'<path class="{cls}" d="{d}"/>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {_num(W)} {_num(H)}" '
            f'width="{_num(W)}" height="{_num(H)}"><style>{STYLE}</style>' + "".join(body) + "</svg>\n")


def build(pack_dir, cache=None, refresh=False):
    spec_path = os.path.join(pack_dir, SPEC)
    with open(spec_path) as f:
        spec = json.load(f)
    pins = spec.get("pins") or {}
    if not pins:
        raise SystemExit(f"{spec_path}: no pins")
    bbox = _bbox(pins, float(spec.get("margin") or DEFAULT_MARGIN))
    if cache is None:
        cache = os.path.join(tempfile.gettempdir(), f"centers-map-{os.path.basename(os.path.normpath(pack_dir))}.json")
    osm = fetch(bbox, cache, refresh)
    proj = Projection(bbox)
    svg = render(osm, proj)
    with open(os.path.join(pack_dir, SVG), "w") as f:
        f.write(svg)
    stamp = (osm.get("osm3s") or {}).get("timestamp_osm_base") or ""
    spec.update({
        "svg": SVG,
        "bbox": bbox,
        "width": proj.width,
        "height": proj.height,
        "attribution": "© OpenStreetMap",
        "attribution_url": "https://www.openstreetmap.org/copyright",
        "osm_date": stamp[:10] or datetime.date.today().isoformat(),
    })
    with open(spec_path, "w") as f:
        json.dump(spec, f, ensure_ascii=False, indent=2)
        f.write("\n")
    return len(svg.encode())


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("pack_dir")
    ap.add_argument("--cache")
    ap.add_argument("--refresh", action="store_true")
    a = ap.parse_args(argv)
    size = build(a.pack_dir, a.cache, a.refresh)
    print(f"{os.path.join(a.pack_dir, SVG)}: {size} bytes")


if __name__ == "__main__":
    sys.exit(main())
