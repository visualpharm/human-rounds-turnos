#!/usr/bin/env python3
"""The decision log: one file per month, and the index that lists them.

    python3 scripts/decisions_index.py --write    # rewrite the index in docs/decisions.md
    python3 scripts/decisions_index.py --check    # exit 1 when the index or a month file is off
    python3 scripts/decisions_index.py --concat   # print every entry, oldest file first

Entries live in `docs/decisions/YYYY-MM.md`, each file holding only the
entries dated in its month, oldest first, a new one appended at the end.
A closed month too big for one file is cut into parts `YYYY-MM-w<week><letter>.md`
(`2026-10-w4b.md`): the same entries in the same order, each part under
`PART_LIMIT` bytes, the month then has no plain `YYYY-MM.md`.
`docs/decisions.md` keeps the rules and an index (entry heading → file)
generated from those files: nothing below its marker is edited by hand.

`--concat` prints the entries of all month files in order, joined the way the
single file joined them. Until 2026-10-26 the log was one file: in the commit
that split it, the old `docs/decisions.md` from its first `## ` line on is
byte for byte this output.
"""
from __future__ import annotations

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INDEX = os.path.join(ROOT, "docs", "decisions.md")
MONTHS_DIR = os.path.join(ROOT, "docs", "decisions")

MARKER = "<!-- Generated by scripts/decisions_index.py --write: do not edit below. -->\n"
MONTH_FILE = re.compile(r"^(\d{4})-(\d{2})(-w\d[a-z])?\.md$")
ENTRY = re.compile(r"^## (\d{4})-(\d{2})-(\d{2}) · (.+)$")
# Entries in the log when it was split into month files (2026-10-26). The log is
# append-only: the total may only grow.
ENTRIES_AT_SPLIT = 183
# A part of a closed month stays under this many bytes (the docs budget, 40 KB).
PART_LIMIT = 40000


def month_of(name: str) -> str:
    """`YYYY-MM` of a file name (`YYYY-MM` or `YYYY-MM-w<week><letter>`)."""
    return name[:7]


def month_header(name: str) -> str:
    """The fixed opening of a month file or of a part of a month; the first entry follows it."""
    month = month_of(name)
    if name == month:
        return (
            f"# Decisions — {month}\n"
            "\n"
            f"Entries dated {month}, oldest first; a new one is appended at the end.\n"
            "Rules and the index of every month: [docs/decisions.md](../decisions.md).\n"
            "\n"
            "---\n"
            "\n"
        )
    part = name[8:]
    return (
        f"# Decisions — {month}, part {part}\n"
        "\n"
        f"Entries dated {month}, part {part} of the closed month, in the order they were appended.\n"
        "The parts follow one another by name; the entries are those of the single month file, unchanged.\n"
        "Rules and the index of every month: [docs/decisions.md](../decisions.md).\n"
        "\n"
        "---\n"
        "\n"
    )


def month_files() -> list[str]:
    """File names (`YYYY-MM` or `YYYY-MM-w<week><letter>`) in docs/decisions/, in order."""
    names = sorted(os.listdir(MONTHS_DIR))
    stray = [n for n in names if not MONTH_FILE.match(n)]
    if stray:
        raise ValueError(
            f"docs/decisions/ holds only YYYY-MM.md files and YYYY-MM-w<week><letter>.md parts, found: {stray}")
    stems = [n[:-3] for n in names]
    both = sorted({month_of(s) for s in stems if s != month_of(s)} & set(stems))
    if both:
        raise ValueError(f"docs/decisions/: {both} is both one file and cut into parts; keep only the parts")
    for stem in stems:
        size = os.path.getsize(os.path.join(MONTHS_DIR, f"{stem}.md"))
        if stem != month_of(stem) and size >= PART_LIMIT:
            raise ValueError(
                f"docs/decisions/{stem}.md is {size} bytes; a part stays under {PART_LIMIT} — cut it by date")
    return stems


def _read(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def month_body(name: str) -> str:
    """The entries of one month file (or part): everything after its header."""
    text = _read(os.path.join(MONTHS_DIR, f"{name}.md"))
    header = month_header(name)
    if not text.startswith(header):
        raise ValueError(
            f"docs/decisions/{name}.md must start with the month header:\n{header}")
    return text[len(header):]


def entries(name: str) -> list[tuple[str, str]]:
    """(date, title) of every entry in one month file (or part), in file order."""
    month = month_of(name)
    body = month_body(name)
    if not body.startswith("## "):
        raise ValueError(f"docs/decisions/{name}.md: the first entry must follow the header")
    found = []
    for line in body.splitlines():
        if not line.startswith("## "):
            continue
        m = ENTRY.match(line)
        if not m:
            raise ValueError(
                f"docs/decisions/{name}.md: heading is not `## YYYY-MM-DD · <title>`: {line}")
        if f"{m.group(1)}-{m.group(2)}" != month:
            raise ValueError(
                f"docs/decisions/{name}.md: entry dated {m.group(1)}-{m.group(2)}-{m.group(3)} "
                f"belongs in docs/decisions/{m.group(1)}-{m.group(2)}.md or a part of that month: {line}")
        found.append((f"{m.group(1)}-{m.group(2)}-{m.group(3)}", m.group(4)))
    return found


def render_index() -> str:
    """docs/decisions.md: the hand-written rules above the marker, the index below."""
    text = _read(INDEX)
    if MARKER not in text:
        raise ValueError(f"docs/decisions.md lost its marker line: {MARKER.strip()}")
    rules = text[:text.index(MARKER)]
    if any(ENTRY.match(line) for line in rules.splitlines()):
        raise ValueError(
            "docs/decisions.md holds an entry: move it to the end of "
            "docs/decisions/<YYYY-MM of its date>.md")
    lines = [rules, MARKER]
    total = 0
    for name in month_files():
        rows = entries(name)
        total += len(rows)
        lines.append(f"\n## {name} · [decisions/{name}.md](decisions/{name}.md) · {len(rows)} entries\n\n")
        lines.extend(f"- {date} · {title}\n" for date, title in rows)
    if total < ENTRIES_AT_SPLIT:
        raise ValueError(
            f"the log is append-only: {total} entries, {ENTRIES_AT_SPLIT} when it was split")
    return "".join(lines)


def concat() -> str:
    """Every entry of every month file, oldest file first, one blank line between files."""
    return "\n".join(month_body(name) for name in month_files())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--concat", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.concat:
            sys.stdout.write(concat())
            return 0
        text = render_index()
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 1
    if args.write:
        with open(INDEX, "w", encoding="utf-8") as fh:
            fh.write(text)
        return 0
    if _read(INDEX) != text:
        print("docs/decisions.md index is stale — run: python3 scripts/decisions_index.py --write",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
