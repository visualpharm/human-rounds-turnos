#!/usr/bin/env python3
"""schema_snapshot.py — the committed picture of the schema at Alembic head.

`alembic/schema-head.txt` lists every table (columns in order, defaults,
NOT NULL), constraint, index, trigger, function and sequence a FRESH install
ends up with, read from the Postgres catalog (`pg_get_*def`), so it does not
depend on the `pg_dump` version. A migration MR therefore shows its schema
change in ONE file, and `test_alembic_revisions.TestSchemaSnapshot` fails when a
revision is added without regenerating it.

    python3 scripts/schema_snapshot.py --write   # regenerate (needs a Postgres
                                                 # that lets this user CREATE DATABASE)
    python3 scripts/schema_snapshot.py --check   # exit 1 if the file is stale

The database used is `TEST_DATABASE_URL` (else `DATABASE_URL`) with its name
swapped for a throwaway one that is dropped afterwards.

Out of scope on purpose: Alembic's own table, the retired runner's
`schema_migrations`, the queue library's `procrastinate_*` objects (its own
schema, deliberately outside the chain) and the optional `pg_trgm` extension
with its search indexes (best-effort at boot, `db_schema._apply_trigrams`).
"""
import os
import re
import sys
from urllib.parse import urlsplit, urlunsplit

import sqlalchemy as sa

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from app.core import sqlcore  # noqa: E402

SNAPSHOT_FILE = os.path.join(ROOT, "alembic", "schema-head.txt")

_EXCLUDED_TABLES = ("alembic_version", "schema_migrations")
_EXCLUDED_PREFIX = "procrastinate_"

_HEADER = (
    "-- Schema of a fresh install at Alembic head {head}.\n"
    "-- Generated by scripts/schema_snapshot.py --write; never edit by hand.\n"
    "-- A migration MR regenerates this file in the same commit.\n")


def _skip(name):
    return name in _EXCLUDED_TABLES or name.startswith(_EXCLUDED_PREFIX)


def alembic_head():
    from alembic.config import Config
    from alembic.script import ScriptDirectory
    cfg = Config()
    cfg.set_main_option("script_location", os.path.join(ROOT, "alembic"))
    return ScriptDirectory.from_config(cfg).get_current_head()


def snapshot(conn):
    """The snapshot text of the `public` schema behind `conn` (a psycopg
    connection with the default tuple rows)."""
    cur = conn.cursor()

    def q(sql, **params):
        # Catalog queries (`pg_class`, `pg_get_*def`, ...) are SQL by nature, not part of the
        # model: `text()` with named parameters, run on the caller's cursor.
        return sqlcore.run(cur, sa.text(sql).bindparams(**params)).fetchall()

    out = [_HEADER.format(head=alembic_head())]
    tables = [r[0] for r in q(
        "SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
        "WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p') ORDER BY 1")
        if not _skip(r[0])]
    for t in tables:
        out.append("TABLE %s" % t)
        for name, typ, notnull, default, ident, gen in q(
                "SELECT a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull, "
                "pg_get_expr(d.adbin, d.adrelid), a.attidentity, a.attgenerated "
                "FROM pg_attribute a LEFT JOIN pg_attrdef d "
                "ON d.adrelid = a.attrelid AND d.adnum = a.attnum "
                "WHERE a.attrelid = ('public.' || quote_ident(:t))::regclass "
                "AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum", t=t):
            line = "  %s %s" % (name, typ)
            if notnull:
                line += " NOT NULL"
            if ident:
                line += " IDENTITY(%s)" % ident
            if gen:
                line += " GENERATED(%s)" % gen
            if default is not None:
                line += " DEFAULT %s" % default
            out.append(line)
        for name, definition in q(
                "SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint "
                "WHERE conrelid = ('public.' || quote_ident(:t))::regclass ORDER BY conname", t=t):
            out.append("  CONSTRAINT %s %s" % (name, definition))
        for (definition,) in q(
                "SELECT indexdef FROM pg_indexes WHERE schemaname = 'public' "
                "AND tablename = :t AND indexdef NOT LIKE '%gin_trgm_ops%' "
                "ORDER BY indexname", t=t):
            out.append("  " + definition)
        for (definition,) in q(
                "SELECT pg_get_triggerdef(oid) FROM pg_trigger "
                "WHERE tgrelid = ('public.' || quote_ident(:t))::regclass "
                "AND NOT tgisinternal ORDER BY tgname", t=t):
            out.append("  " + definition)
        out.append("")
    for name, typ, start, inc, owner in q(
            "SELECT s.sequencename, s.data_type::text, s.start_value, s.increment_by, "
            "COALESCE(t.relname || '.' || a.attname, '-') FROM pg_sequences s "
            "LEFT JOIN pg_class sc ON sc.relname = s.sequencename "
            "AND sc.relnamespace = 'public'::regnamespace "
            "LEFT JOIN pg_depend d ON d.objid = sc.oid AND d.deptype IN ('a', 'i') "
            "LEFT JOIN pg_class t ON t.oid = d.refobjid "
            "LEFT JOIN pg_attribute a ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid "
            "WHERE s.schemaname = 'public' ORDER BY 1"):
        if _skip(name) or (owner != "-" and _skip(owner.split(".")[0])):
            continue
        out.append("SEQUENCE %s %s start %s inc %s owned-by %s" % (name, typ, start, inc, owner))
    funcs = q(
        "SELECT p.proname, pg_get_functiondef(p.oid) FROM pg_proc p "
        "WHERE p.pronamespace = 'public'::regnamespace "
        "AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e') "
        "ORDER BY 1, p.oid::text")
    for name, definition in funcs:
        if _skip(name):
            continue
        out.append("")
        out.append(definition.strip())
    return "\n".join(out).rstrip("\n") + "\n"


def _base_url():
    url = os.environ.get("TEST_DATABASE_URL") or os.environ.get("DATABASE_URL")
    if not url:
        sys.exit("schema_snapshot: set TEST_DATABASE_URL (or DATABASE_URL)")
    return url


def _drop_database(cur, name):
    sqlcore.run(cur, sa.text("DROP DATABASE IF EXISTS " + sqlcore.quote_identifier(name) + " WITH (FORCE)"))


def build_fresh_snapshot():
    """Boots a throwaway database through the real `db._connect()` (Alembic
    from empty to head) and returns its snapshot text."""
    import psycopg
    sys.path.insert(0, ROOT)
    from app.core import db
    from app.core import db_schema
    p = urlsplit(_base_url())
    name = "sana_turnos_schema_snapshot_%d" % os.getpid()
    maint = urlunsplit((p.scheme, p.netloc, "/postgres", p.query, p.fragment))
    url = urlunsplit((p.scheme, p.netloc, "/" + name, p.query, p.fragment))
    with psycopg.connect(maint, autocommit=True, connect_timeout=5) as c, c.cursor() as cur:
        _drop_database(cur, name)
        sqlcore.run(cur, sa.text("CREATE DATABASE " + sqlcore.quote_identifier(name)))
    old = os.environ.get("DATABASE_URL")
    try:
        os.environ["DATABASE_URL"] = url
        db_schema._ensured.clear()
        db._connect().close()
        with psycopg.connect(url) as conn:
            return snapshot(conn)
    finally:
        if old is None:
            os.environ.pop("DATABASE_URL", None)
        else:
            os.environ["DATABASE_URL"] = old
        db_schema._ensured.clear()
        db.close_pools()
        with psycopg.connect(maint, autocommit=True, connect_timeout=5) as c, c.cursor() as cur:
            _drop_database(cur, name)


def main(argv):
    mode = argv[1] if len(argv) > 1 else "--check"
    if mode not in ("--write", "--check"):
        sys.exit(__doc__)
    text = build_fresh_snapshot()
    if mode == "--write":
        with open(SNAPSHOT_FILE, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        print("wrote %s" % os.path.relpath(SNAPSHOT_FILE, ROOT))
        return 0
    with open(SNAPSHOT_FILE, encoding="utf-8", newline="") as f:
        current = f.read()
    if current == text:
        print("schema snapshot is current")
        return 0
    print("schema snapshot is STALE — run: python3 scripts/schema_snapshot.py --write")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
