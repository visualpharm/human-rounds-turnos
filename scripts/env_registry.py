#!/usr/bin/env python3
"""The registry of every `TURNOS_*` variable the product code reads: `docs/env-registry.md`.

    python3 scripts/env_registry.py --write    # regenerate the registry
    python3 scripts/env_registry.py --check    # exit 1 when it is stale

A name is READ when a non-test file holds it as a string constant (Python: the AST, docstrings
excluded; shell/JS/YAML/Dockerfile: the text). A constant ending in `_` is a FAMILY — a prefix the
code completes at run time (`TURNOS_PUCO_GWT_PERM_` + coverage kind). A field of a pydantic-settings
class (`Field(<default>, validation_alias="<NAME>")` in a class body, core/settings.py) is read by
that class, with that default — and is listed even without the `TURNOS_` prefix (`HOST`, `PORT`,
`DATABASE_URL`). Nothing below the marker of the registry is edited by hand: a new variable is a new
row after `--write`, and `tests/test_env_registry.py` fails until it is there. Reading stays where it
is (`core/config.get` for the settings that the panel may override, `core/settings.py` for the
process keys); this file only says where each name is read, with which default, and who sets it.
"""
from __future__ import annotations

import argparse
import ast
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REGISTRY = os.path.join(ROOT, "docs", "env-registry.md")

NAME = re.compile(r"TURNOS_[A-Z0-9_]+")
EXACT = re.compile(r"^TURNOS_[A-Z0-9_]+$")
# A settings field may name any environment variable, not only a `TURNOS_*` one.
FIELD_NAME = re.compile(r"^[A-Z][A-Z0-9_]*$")
JS_ENV = re.compile(r"process\.env(?:\.|\[[\"'])(TURNOS_[A-Z0-9_]+)")

# Not product code: tests, vendored kit, agent tooling, docs, catalogs, data packs.
SKIP_DIRS = {"tests", "vendor", ".claude", "docs", "locales", "packs", "node_modules", ".git", "__pycache__",
             "ci-artifacts", "test-results", "playwright-report", "coverage", "storybook-static", "stories",
             "design-plans", ".ci-asgi"}
WALK_SKIP = {".git", "node_modules", "__pycache__", "ci-artifacts", "test-results", "playwright-report", "coverage",
             "storybook-static", ".claude", ".ci-asgi"}
CODE_SUFFIXES =(".py", ".sh", ".js", ".mjs")
# Where a variable is documented as set, by kind (first match wins per file).
SETTERS = (
    (".env.example", ".env.example"),
    (".gitlab-ci.yml", "CI"),
    ("Dockerfile", "Dockerfile"),
    ("docker-compose", "compose"),
    ("package.json", "package.json"),
    ("docs/deploy/", "deploy docs"),
    ("docs/operations/", "deploy docs"),
    ("docs/UPGRADING.md", "deploy docs"),
    ("docs/architecture/deploy.md", "deploy docs"),
    ("docs/policies/HIGH_AVAILABILITY.md", "deploy docs"),
    ("docs/policies/INCIDENT_RESPONSE.md", "deploy docs"),
)
# New English name -> legacy aliases still read as a fallback (never removed without knowing what the
# installations set; the question is the product owner's).
ALIAS_PAIRS = (
    ("TURNOS_AI_ABUSE_FAILS", "TURNOS_IA_ABUSO_FALLOS"),
    ("TURNOS_AI_ABUSE_MIN", "TURNOS_IA_ABUSO_MIN"),
    ("TURNOS_AI_ABUSE_OFF", "TURNOS_IA_ABUSO_OFF"),
    ("TURNOS_AI_FORCE", "TURNOS_IA_FORZAR"),
    ("TURNOS_AI_HEALTH_OFF", "TURNOS_IA_SALUD_OFF"),
    ("TURNOS_AI_PROBE_MIN", "TURNOS_IA_PROBE_MIN"),
    ("TURNOS_WAITLIST_OFF", "TURNOS_LISTA_ESPERA_OFF"),
    ("TURNOS_WAITLIST_INTERVAL_MIN", "TURNOS_LISTA_ESPERA_INTERVAL_MIN"),
    ("TURNOS_REMINDERS_OFF", "TURNOS_RECORDATORIOS_OFF"),
    ("TURNOS_REMINDER_INTERVAL_MIN", "TURNOS_RECORDATORIO_INTERVAL_MIN"),
    ("TURNOS_SISA_USER", "TURNOS_SISA_USUARIO"),
    ("TURNOS_SISA_PASS", "TURNOS_SISA_CLAVE"),
    ("TURNOS_THEME_DEFAULT", "TURNOS_TEMA_DEFAULT"),
    ("TURNOS_SEARCHES_PER_DAY", "TURNOS_BUSQUEDAS_PER_DAY"),
)
LEGACY_OF = {old: new for new, old in ALIAS_PAIRS}

MARKER = "<!-- Generated by scripts/env_registry.py --write: do not edit below. -->\n"
HEADER = (
    "# `TURNOS_*` registry\n"
    "\n"
    "Every `TURNOS_*` name the product code names (tests, vendored code and agent tooling excluded; a read, a write or a mere\n"
    "reference counts): where it appears,\n"
    "the default the call site passes, who is documented as setting it and what it is for. Generated by\n"
    "`python3 scripts/env_registry.py --write`; `tests/test_env_registry.py` fails on a stale file, on a name read in\n"
    "code that is missing here and on a name in the architecture docs that no code reads. A *family* (`NAME_*`) is a\n"
    "prefix the code completes at run time; a *legacy alias* is the old Spanish name of a variable that still works as a\n"
    "fallback (removing one needs to know what each installation has set); a *test seam* exists only for the test suite.\n"
    "The process keys declared in `core/settings.py` are listed too when they have no `TURNOS_` prefix (`HOST`, `PORT`,\n"
    "`DATABASE_URL`).\n"
    "\n"
    "How a value is read is a property of the call site, not of the name: `config.get` / `config.get_text` consult the\n"
    "panel's database override first, then the environment, then `.env` (`TURNOS_CONFIG_LOCK` freezes the override);\n"
    "`<Class>.current` (`core/settings.py`) reads the environment only, or the environment and then the env file\n"
    "(`DatabaseSettings`, `InstallationSettings`), never the database; `os.environ` / `_env` helpers read the environment\n"
    "only.\n"
    "\n"
)


def _files():
    """Tracked files when there is a git checkout, else a walk of the tree (same answer on a clean tree)."""
    try:
        out = subprocess.run(["git", "-C", ROOT, "ls-files"], capture_output=True, text=True, check=True).stdout
        names = [n for n in out.split("\n") if n]
        if names:
            return sorted(names)
    except (OSError, subprocess.CalledProcessError):
        pass
    names = []
    for base, dirs, files in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in WALK_SKIP]
        for f in files:
            names.append(os.path.relpath(os.path.join(base, f), ROOT))
    return sorted(names)


def _read(rel):
    try:
        with open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
            return fh.read()
    except (OSError, UnicodeDecodeError):
        return ""


def is_code(rel):
    if rel == "scripts/env_registry.py":
        return False  # its alias table names variables without reading them
    parts = rel.split("/")
    if parts[0] in SKIP_DIRS or any(p in SKIP_DIRS for p in parts[:-1]):
        return False
    return rel.endswith(CODE_SUFFIXES)


def _callee(node):
    f = node.func
    parts = []
    while isinstance(f, ast.Attribute):
        parts.append(f.attr)
        f = f.value
    if isinstance(f, ast.Name):
        parts.append(f.id)
    return ".".join(reversed(parts))


def _comment_above(lines, lineno):
    """The contiguous `#` comment block right above 1-based `lineno`, as one line of text."""
    out = []
    i = lineno - 2
    while i >= 0 and lines[i].strip().startswith("#") and not lines[i].startswith("#!"):
        out.append(lines[i].strip().lstrip("#").strip())
        i -= 1
    return " ".join(reversed(out))


def scan_python(rel, text, found):
    """Add the TURNOS_* constants of one Python file to `found` ({name: info})."""
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return
    docstrings = set()
    for n in ast.walk(tree):
        if isinstance(n, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            if n.body and isinstance(n.body[0], ast.Expr) and isinstance(n.body[0].value, ast.Constant):
                docstrings.add(id(n.body[0].value))
    lines = text.split("\n")
    call_args = {}
    for n in ast.walk(tree):
        if isinstance(n, ast.Call) and n.args and isinstance(n.args[0], ast.Constant):
            call_args[id(n.args[0])] = n
    for n in ast.walk(tree):
        if not (isinstance(n, ast.Constant) and isinstance(n.value, str)) or id(n) in docstrings:
            continue
        if not EXACT.match(n.value):
            continue
        info = found.setdefault(n.value, {"files": set(), "reads": set(), "comment": ""})
        info["files"].add(rel)
        call = call_args.get(id(n))
        if call is not None:
            default = None
            second = call.args[1] if len(call.args) > 1 else None
            # `_env2(new, old)`: the second name is the legacy alias, not a default
            alias = isinstance(second, ast.Constant) and isinstance(second.value, str) and EXACT.match(second.value)
            if second is not None and not alias:
                default = ast.unparse(second)
            for kw in call.keywords:
                if kw.arg == "default":
                    default = ast.unparse(kw.value)
            info["reads"].add((_callee(call), default))
        if not info["comment"]:
            info["comment"] = _comment_above(lines, n.lineno)
    constants = {t.id: ast.unparse(s.value) for s in tree.body if isinstance(s, ast.Assign)
                 and isinstance(s.value, ast.Constant) for t in s.targets if isinstance(t, ast.Name)}
    for cls in (n for n in ast.walk(tree) if isinstance(n, ast.ClassDef)):
        for stmt in cls.body:
            field = settings_field(stmt)
            if field is None:
                continue
            name, default = field
            default = constants.get(default, default)
            info = found.setdefault(name, {"files": set(), "reads": set(), "comment": ""})
            info["files"].add(rel)
            info["reads"].add((f"{cls.name}.current", default))
            if not info["comment"]:
                info["comment"] = _comment_above(lines, stmt.lineno)


def settings_field(stmt):
    """`(name, default)` of `x: T = Field(<default>, validation_alias="<NAME>")`, else None."""
    call = stmt.value if isinstance(stmt, ast.AnnAssign) else None
    if not (isinstance(call, ast.Call) and _callee(call) in ("Field", "pydantic.Field")):
        return None
    alias = next((kw.value for kw in call.keywords if kw.arg == "validation_alias"), None)
    if not (isinstance(alias, ast.Constant) and isinstance(alias.value, str) and FIELD_NAME.match(alias.value)):
        return None
    default = ast.unparse(call.args[0]) if call.args else None
    for kw in call.keywords:
        if kw.arg == "default":
            default = ast.unparse(kw.value)
    return alias.value, default


def scan_text(rel, text, found):
    """Shell: every TURNOS_* token; JS/MJS: only `process.env.NAME` / `process.env["NAME"]` (other names in a
    browser script are JS constants, not environment)."""
    lines = text.split("\n")
    js = not rel.endswith(".sh")
    for i, line in enumerate(lines, 1):
        names = JS_ENV.findall(line) if js else [m.group(0) for m in NAME.finditer(line)]
        for name in names:
            m = NAME.fullmatch(name)
            if not m:
                continue
            info = found.setdefault(m.group(0), {"files": set(), "reads": set(), "comment": ""})
            info["files"].add(rel)
            if not info["comment"]:
                info["comment"] = _comment_above(lines, i)


def env_example_notes(text):
    """{name: comment block above its line} from `.env.example` (commented examples count)."""
    notes = {}
    lines = text.split("\n")
    for i, line in enumerate(lines, 1):
        m = re.match(r"^#?\s*(TURNOS_[A-Z0-9_]+)=", line)
        if m and m.group(1) not in notes:
            notes[m.group(1)] = _comment_above(lines, i)
    return notes


def collect():
    """({name: info}, {name: [setter kinds]}, {name: tests?}) over the tracked tree."""
    found = {}
    setters = {}
    in_tests = set()
    notes = {}
    setter_texts = []
    test_texts = []
    for rel in _files():
        text = None
        if rel == ".env.example":
            text = _read(rel)
            notes = env_example_notes(text)
        if is_code(rel):
            text = _read(rel)
            if rel.endswith(".py"):
                scan_python(rel, text, found)
            else:
                scan_text(rel, text, found)
        kind = next((k for p, k in SETTERS if rel.startswith(p) or rel.endswith("/" + p)), None)
        if kind is not None:
            setter_texts.append((kind, text if text is not None else _read(rel)))
        if rel.startswith("tests/") and rel.endswith((".py", ".mjs")):
            test_texts.append(_read(rel))
    # `TURNOS_*` names, plus the settings fields without that prefix (`HOST`, `PORT`, `DATABASE_URL`).
    others = sorted(n for n in found if not n.startswith("TURNOS_"))
    names = re.compile(r"TURNOS_[A-Z0-9_]+" + "".join(rf"|\b{re.escape(n)}\b" for n in others))
    for kind, text in setter_texts:
        for m in names.finditer(text):
            setters.setdefault(m.group(0), set()).add(kind)
    for text in test_texts:
        in_tests.update(m.group(0) for m in names.finditer(text))
    for name, info in found.items():
        note = notes.get(name) or info["comment"]
        info["note"] = _one_line(note)
    return found, setters, in_tests


def _one_line(text):
    text = " ".join((text or "").split()).replace("|", "/")
    if len(text) > 130:
        text = text[:127].rsplit(" ", 1)[0] + "..."
    return text or "—"


def read_how(info):
    reads = sorted(info["reads"], key=lambda r: (r[0], str(r[1])))
    if not reads:
        return "referenced", "—"
    callees = sorted({c for c, _ in reads})
    defaults = sorted({d for _, d in reads if d is not None})
    shown = ", ".join(f"`{d[:36]}`" for d in defaults[:2]).replace("|", "/") or "—"
    if len(defaults) > 2:
        shown += f" +{len(defaults) - 2}"
    return ", ".join(f"`{c}`" for c in callees[:3]) + (f" +{len(callees) - 3}" if len(callees) > 3 else ""), shown


def _where(files):
    files = sorted(files)
    shown = ", ".join(f"`{f}`" for f in files[:3])
    return shown + (f" +{len(files) - 3}" if len(files) > 3 else "")


def flags(name, info, found):
    out = []
    if name.endswith("_"):
        out.append(f"family `{name}*`")
    if name in LEGACY_OF:
        out.append(f"legacy alias of `{LEGACY_OF[name]}`")
    if name.startswith("TURNOS_TEST_") or "test seam" in info["note"].lower():
        out.append("test seam")
    return ", ".join(out)


def render():
    found, setters, in_tests = collect()
    rows = []
    for name in sorted(found):
        info = found[name]
        how, default = read_how(info)
        who = ", ".join(sorted(setters.get(name, ()))) or ("tests only" if name in in_tests else "—")
        tag = flags(name, info, found)
        note = info["note"] + (f" ({tag})" if tag else "")
        rows.append(f"| `{name}` | {_where(info['files'])} | {how} | {default} | {who} | {note} |")
    body = ["| Name | Read in | Read by | Default | Documented as set in | Note |",
            "|---|---|---|---|---|---|"] + rows
    return HEADER + MARKER + "\n" + f"{len(rows)} names.\n\n" + "\n".join(body) + "\n"


def registry_names(text=None):
    """The names listed in the registry file."""
    text = text if text is not None else _read("docs/env-registry.md")
    return set(re.findall(r"^\| `([A-Z][A-Z0-9_]*)` \|", text, re.M))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render()
    if args.write:
        with open(REGISTRY, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"wrote {os.path.relpath(REGISTRY, ROOT)}")
        return 0
    if args.check:
        if _read("docs/env-registry.md") != text:
            print("docs/env-registry.md is stale — run: python3 scripts/env_registry.py --write")
            return 1
        print("docs/env-registry.md is current")
        return 0
    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
